"""Export model outputs to dashboard/data.js for the static dashboard.

Run after predict_eta.py and notify.py:
    python src/build_dashboard.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
DASHBOARD_DATA = ROOT / "dashboard/data.js"

ORDER_COLS = ["Order_ID", "Delivery_person_ID", "City", "Time_Ordered", "Time_Order_picked",
              "Weather_conditions", "Weather_Label", "Road_traffic_density", "Traffic_Label",
              "Festival", "Festival_Label", "multiple_deliveries", "Type_of_vehicle", "Distance_km",
              "Predicted_ETA_min", "Estimated_Arrival", "Risk_Score", "Risk_Category", "Risk_Drivers"]
METRIC_LABELS = {
    "Training rows (historical, valid)": "training_rows",
    "Hold-out MAE (min)": "holdout_mae",
    "Hold-out RMSE (min)": "holdout_rmse",
    "Hold-out R2": "holdout_r2",
    "Baseline MAE: predict the mean (min)": "baseline_mae",
    "Backtest MAE on active batch (min)": "backtest_mae",
}


def build():
    orders = pd.read_csv(OUT / "active_deliveries_ZC_predicted.csv")
    summary = pd.read_excel(OUT / "active_deliveries_ZC_predicted.xlsx", sheet_name="Summary", header=None)
    metrics = {METRIC_LABELS[k]: float(v) for k, v in zip(summary[0], summary[1]) if k in METRIC_LABELS}

    dispatch_path = OUT / "notifications/escalation_dispatch_log.csv"
    emails = {}
    if dispatch_path.exists():
        dispatch = pd.read_csv(dispatch_path)
        for oid, grp in dispatch.groupby("Order_ID"):
            emails[oid] = {row.recipient_role: row.status for row in grp.itertuples()}

    records = orders[ORDER_COLS].to_dict("records")
    for r in records:
        r["Emails"] = emails.get(r["Order_ID"], {})

    data = {
        "generated_from": "outputs/active_deliveries_ZC_predicted.csv",
        "eta_updated_at": str(orders["ETA_Updated_At"].iloc[0]),
        "metrics": metrics,
        "orders": records,
    }
    DASHBOARD_DATA.write_text("// Generated by src/build_dashboard.py. Do not edit by hand.\n"
                              f"window.ETA_DATA = {json.dumps(data, indent=1)};\n")
    return data


if __name__ == "__main__":
    d = build()
    print(f"Wrote {DASHBOARD_DATA.relative_to(ROOT)}: {len(d['orders'])} orders, metrics {d['metrics']}")
